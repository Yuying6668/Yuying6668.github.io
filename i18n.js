(function () {
  const LANGS = ['en', 'da', 'zh'];
  const HTML_LANG = { en: 'en', da: 'da', zh: 'zh-CN' };
  const nodes = [...document.querySelectorAll('[data-i18n]')];
  nodes.forEach(n => { n.dataset.i18nEn = n.innerHTML; });   // English source = the HTML itself

  function apply(lang) {
    if (!LANGS.includes(lang)) lang = 'en';
    const dict = I18N[lang] || {};
    nodes.forEach(n => {
      const key = n.dataset.i18n;
      n.innerHTML = lang === 'en' ? n.dataset.i18nEn : (dict[key] ?? n.dataset.i18nEn);
    });
    document.documentElement.lang = HTML_LANG[lang];
    document.documentElement.dataset.lang = lang;
    document.querySelectorAll('.lang-switch button').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    try { localStorage.setItem('lang', lang); } catch (e) {}
    window.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  document.querySelectorAll('.lang-switch button').forEach(b => b.addEventListener('click', () => apply(b.dataset.lang)));
  let saved = 'en';
  try { saved = localStorage.getItem('lang') || 'en'; } catch (e) {}
  if (saved !== 'en') apply(saved);
})();
